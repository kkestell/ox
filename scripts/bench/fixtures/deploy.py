# Generates and checks the deploy benchmark task: a shell script that renders
# configuration files from heredocs, with changes inside the heredoc bodies.
#
#   python3 deploy.py setup|check

import subprocess
import sys
from pathlib import Path

SCRIPT = r"""#!/usr/bin/env bash
# Renders the configuration for every service into an output directory.
#
#   ./deploy.sh render OUT_DIR
set -euo pipefail

SERVICES="api:8080 worker:8081 billing:8082 search:8083 admin:8084"

usage() {
    cat <<'EOF'
Usage: deploy.sh render OUT_DIR

Renders nginx, systemd, and environment files for: $SERVICES
Run `deploy.sh render ./out` and copy ./out to the host.
EOF
}

render_nginx() {
    local name="$1" port="$2"
    cat > "$OUT/$name.nginx.conf" <<EOF
server {
    listen 80;
    server_name $name.example.com;

    location / {
        proxy_pass http://127.0.0.1:$port;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_read_timeout 30s;
    }

    location /healthz {
        return 200 'ok';
    }
}
EOF
}

render_unit() {
    local name="$1" port="$2"
    cat > "$OUT/$name.service" <<EOF
[Unit]
Description=$name service
After=network.target

[Service]
ExecStart=/opt/app/bin/$name --port $port
Restart=on-failure
Environment="LOG_FORMAT=json"
EnvironmentFile=/etc/app/$name.env

[Install]
WantedBy=multi-user.target
EOF
}

render_env() {
    local name="$1" port="$2"
    cat > "$OUT/$name.env" <<'EOF'
# Generated by deploy.sh; edit the template, not this file.
DATABASE_URL=postgres://app@db.internal:5432/app
CACHE_URL=redis://cache.internal:6379/0
EOF
    printf 'PORT=%s\nSERVICE=%s\n' "$port" "$name" >> "$OUT/$name.env"
}

render_index() {
    python3 - "$OUT" <<'PY'
import json
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
files = sorted(path.name for path in out.iterdir() if path.name != "index.json")
services = sorted({name.split(".")[0] for name in files})
index = {"services": services, "files": files}
(out / "index.json").write_text(json.dumps(index, indent=2) + "\n")
PY
}

main() {
    if [ "$#" -ne 2 ] || [ "$1" != render ]; then
        usage >&2
        exit 2
    fi
    OUT="$2"
    mkdir -p "$OUT"
    for entry in $SERVICES; do
        name="${entry%%:*}"
        port="${entry##*:}"
        render_nginx "$name" "$port"
        render_unit "$name" "$port"
        render_env "$name" "$port"
    done
    render_index
}

main "$@"
"""

CHANGES = r"""# Deployment changes

Make exactly these changes to deploy.sh. Lines are shown exactly as they must
appear in deploy.sh.

1. Add the reports service on port 8085 to the end of `SERVICES`.
2. In the nginx template, add this line directly after the `X-Real-IP` line:

        proxy_set_header X-Forwarded-Proto \$scheme;

3. In the nginx template, change the read timeout from `30s` to `120s`.
4. In the nginx template, change the `/healthz` block's response to
   `return 200 'ok\n';` (a literal backslash and `n` inside the quotes).
5. In the systemd unit template, add this line directly after the
   `Restart=on-failure` line:

        RestartSec=5

6. In the systemd unit template, change `Environment="LOG_FORMAT=json"` to
   `Environment="LOG_FORMAT=json" "LOG_LEVEL=info"`.
7. In the environment template, change the cache database from `/0` to `/2`, and
   add this line after the `CACHE_URL` line:

        QUEUE_URL=amqp://guest:guest@mq.internal:5672/%2F

8. In the Python index script, sort the services in reverse order, and add a
   `"count"` key with the number of services after `"files"`, so the line that
   builds the index reads:

        index = {"services": services, "files": files, "count": len(services)}

   and the services line reads:

        services = sorted({name.split(".")[0] for name in files}, reverse=True)

9. In the usage message, add this line after the `Run ...` line:

        Set DEPLOY_DRY_RUN=1 to print instead of write (not yet supported).
"""


def expected():
    s = SCRIPT
    swaps = [
        ("admin:8084\"", "admin:8084 reports:8085\""),
        (
            "X-Real-IP \\$remote_addr;\n",
            "X-Real-IP \\$remote_addr;\n        proxy_set_header X-Forwarded-Proto \\$scheme;\n",
        ),
        ("proxy_read_timeout 30s;", "proxy_read_timeout 120s;"),
        ("return 200 'ok';", "return 200 'ok\\n';"),
        ("Restart=on-failure\n", "Restart=on-failure\nRestartSec=5\n"),
        ('Environment="LOG_FORMAT=json"', 'Environment="LOG_FORMAT=json" "LOG_LEVEL=info"'),
        (
            "CACHE_URL=redis://cache.internal:6379/0\n",
            "CACHE_URL=redis://cache.internal:6379/2\nQUEUE_URL=amqp://guest:guest@mq.internal:5672/%2F\n",
        ),
        (
            'services = sorted({name.split(".")[0] for name in files})',
            'services = sorted({name.split(".")[0] for name in files}, reverse=True)',
        ),
        (
            'index = {"services": services, "files": files}',
            'index = {"services": services, "files": files, "count": len(services)}',
        ),
        (
            "copy ./out to the host.\n",
            "copy ./out to the host.\nSet DEPLOY_DRY_RUN=1 to print instead of write (not yet supported).\n",
        ),
    ]
    for old, new in swaps:
        assert s.count(old) == 1, old
        s = s.replace(old, new)
    return s


def setup():
    path = Path("deploy.sh")
    path.write_text(SCRIPT)
    path.chmod(0o755)
    Path("CHANGES.md").write_text(CHANGES)
    for args in (["init", "-q"], ["add", "-A"]):
        subprocess.run(["git", *args], check=True)
    subprocess.run(
        ["git", "-c", "user.name=bench", "-c", "user.email=bench@example.com", "commit", "-qm", "Initial"],
        check=True,
    )


def check():
    got = Path("deploy.sh").read_text()
    want = expected()
    if got != want:
        lines = [i + 1 for i, (a, b) in enumerate(zip(want.splitlines(), got.splitlines())) if a != b]
        print(f"FAIL: deploy.sh differs from the expected file; first differing lines {lines[:10]},"
              f" {len(got.splitlines())} lines instead of {len(want.splitlines())}")
        raise SystemExit(1)
    print("PASS")


if __name__ == "__main__":
    {"setup": setup, "check": check}[sys.argv[1]]()
